CREATE TABLE IF NOT EXISTS roles (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    fullname VARCHAR(150) NOT NULL,
    password VARCHAR(100) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    role_id INT NOT NULL,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

CREATE TABLE IF NOT EXISTS categories (
    cid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cname VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS lands (
    lid INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lname VARCHAR(255) NOT NULL,
    description CLOB NOT NULL,
    date_create TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    picture VARCHAR(255) NOT NULL DEFAULT '',
    area INT NOT NULL DEFAULT 0,
    address VARCHAR(255) NOT NULL,
    count_views INT NOT NULL DEFAULT 0,
    cid INT NOT NULL,
    CONSTRAINT fk_lands_category FOREIGN KEY (cid) REFERENCES categories(cid)
);

CREATE TABLE IF NOT EXISTS vnecontact (
    ct_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ct_fullname VARCHAR(150) NOT NULL,
    ct_email VARCHAR(150) NOT NULL,
    ct_subject VARCHAR(255) NOT NULL,
    ct_content CLOB NOT NULL
);

CREATE TABLE IF NOT EXISTS persistent_logins (
    username VARCHAR(64) NOT NULL,
    series VARCHAR(64) PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    last_used TIMESTAMP NOT NULL
);
